from pathlib import Path
from playwright.sync_api import sync_playwright,expect
root=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1000});errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:5173',wait_until='networkidle')
 expect(page.locator('h1')).to_have_text('A clearer picture of access.')
 page.get_by_role('button',name='Hospital directory',exact=True).click()
 page.get_by_role('textbox',name='Search hospitals').fill('Albany Medical Center')
 expect(page.locator('tbody tr')).to_have_count(2)
 page.get_by_role('combobox',name='Review grade').select_option('A')
 expect(page.get_by_text('No hospitals match these filters')).to_be_visible()
 page.get_by_role('combobox',name='Review grade').select_option('D')
 page.get_by_role('button',name='Albany Medical Center Hospital',exact=True).click()
 expect(page.get_by_role('dialog')).to_be_visible()
 expect(page.get_by_role('heading',name='Albany Medical Center Hospital',exact=True)).to_be_visible()
 page.get_by_role('button',name='Reviewer notes',exact=True).click()
 page.get_by_label('Review notes',exact=True).fill('Browser test: verified source pending.')
 page.get_by_role('button',name='Save note',exact=True).click()
 expect(page.get_by_role('button',name='Saved in this browser')).to_be_visible()
 page.keyboard.press('Escape')
 expect(page.get_by_role('dialog')).to_have_count(0)
 page.get_by_role('button',name='Albany Medical Center Hospital',exact=True).click()
 page.get_by_role('button',name='Reviewer notes',exact=True).click()
 expect(page.get_by_label('Review notes',exact=True)).to_have_value('Browser test: verified source pending.')
 page.keyboard.press('Escape')
 page.get_by_role('textbox',name='Search hospitals').fill('')
 page.get_by_role('combobox',name='Review grade').select_option('All grades')
 with page.expect_download() as download:
  page.get_by_role('button',name='Export data',exact=True).click()
 assert download.value.suggested_filename.endswith('.csv')
 page.get_by_role('button',name='Statewide map',exact=True).click()
 expect(page.locator('.map-point').first).to_be_visible()
 page.locator('.map-point').first.click()
 assert page.locator('.drawer,.map-location-list').count()>0
 if page.locator('.drawer').count():page.keyboard.press('Escape')
 page.get_by_role('button',name='Evidence & review',exact=True).click()
 expect(page.get_by_role('heading',name='Follow the evidence.')).to_be_visible()
 page.get_by_role('button',name='Methodology',exact=True).click()
 expect(page.get_by_text('Evidence you can inspect.')).to_be_visible()
 page.screenshot(path=str(root/'methodology.png'),full_page=True,animations='disabled')
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='Open navigation').click()
 page.get_by_role('button',name='Overview',exact=True).click()
 expect(page.locator('h1')).to_be_visible()
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile page overflows horizontally'
 page.screenshot(path=str(root/'mobile.png'),full_page=True,animations='disabled')
 print('Browser checks passed: search, combined filters, detail drawer, persisted notes, export, map selection, navigation, and mobile layout.')
 print('Browser JavaScript errors:',errors)
 assert not errors
 b.close()
